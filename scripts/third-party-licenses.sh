#!/bin/sh
# Writes THIRD_PARTY_LICENSES: the licence and NOTICE files of every module linked into the release
# binaries (all four goreleaser targets), the Go standard library's licence and the embedded fonts'
# OFL. `make generate` runs it; `make check-gen` (CI) fails when the committed file is stale.
set -eu
cd "$(dirname "$0")/.."
out=THIRD_PARTY_LICENSES
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
for t in darwin/arm64 darwin/amd64 linux/arm64 linux/amd64; do
  CGO_ENABLED=0 GOOS=${t%/*} GOARCH=${t#*/} go list -deps \
    -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/ccswap >>"$tmp/deps"
done
LC_ALL=C sort -u "$tmp/deps" >"$tmp/mods"
rule='================================================================================'

section() { # title, then files
  printf '%s\n%s\n' "$rule" "$1"
  shift
  for f in "$@"; do
    printf -- '--- %s\n\n' "$(basename "$f")"
    tr -d '\r' <"$f" # a few upstream files have CRLF line ends
    printf '\n'
  done
}

{
  printf 'Licences of the third-party code in ccswap binaries.\n'
  printf 'Generated by scripts/third-party-licenses.sh from the module cache; do not edit.\n\n'
  section "Go standard library and runtime (https://go.dev)" "$(go env GOROOT)/LICENSE"
  while read -r path version dir; do
    files=$(find "$dir" -maxdepth 1 -type f \( -iname 'licen[cs]e*' -o -iname 'copying*' -o -iname 'notice*' \) | LC_ALL=C sort)
    if [ -z "$files" ]; then
      echo "$0: no licence file in $path $version ($dir)" >&2
      exit 1
    fi
    # shellcheck disable=SC2086 # module cache paths hold no spaces
    section "$path $version" $files
  done <"$tmp/mods"
  section "Geologica font (embedded in the web page)" internal/web/fonts/OFL-Geologica.txt
  section "JetBrains Mono font (embedded in the web page)" internal/web/fonts/OFL-JetBrainsMono.txt
} >"$tmp/out"
mv "$tmp/out" "$out"
